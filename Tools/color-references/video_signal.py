"""Reference decodes for 10-bit Y'CbCr video, computed with colour-science.

For each camera input: the published 18% gray and 90% white code values (or the
colour-science encoding where no code value is published) and one chromatic patch,
coded in legal (narrow) and full range, decoded to linear sRGB / Rec.709 scene light.

Run: uv run Tools/color-references/video_signal.py > Packages/EmulsionCore/Tests/EmulsionCoreTests/VideoSignalReferences.swift
"""

import warnings

warnings.filterwarnings("ignore")

import colour  # noqa: E402
import numpy as np  # noqa: E402
from colour.models import (  # noqa: E402
    RGB_COLOURSPACES,
    log_decoding_AppleLogProfile,
    log_decoding_ARRILogC3,
    log_decoding_SLog3,
    log_decoding_VLog,
    log_encoding_AppleLogProfile,
    log_encoding_ARRILogC3,
    oetf_BT2100_HLG,
    oetf_inverse_BT2100_HLG,
)

BITS = 10
# BT.2408: 18% gray at 38% HLG signal; Emulsion scales HLG so that lands on 0.18.
HLG_SCENE_SCALE = 0.18 / float(oetf_inverse_BT2100_HLG(0.38))


def legal_code(signal):
    """Normalized signal E' -> 10-bit legal-range code (BT.2100 narrow range)."""
    return int(round(64 + 876 * signal))


def hlg(signal):
    return oetf_inverse_BT2100_HLG(signal) * HLG_SCENE_SCALE


# (Swift case, YCbCr matrix, gamut, decode(normalized signal E'), [(label, legal Y' code, source)])
INPUTS = [
    ("sLog3SGamut3Cine", "bt709", "S-Gamut3.Cine",
     lambda e: log_decoding_SLog3(e, in_normalised_code_value=False),
     [("gray", 420, "Sony S-Log3 technical summary: 18% = 420"),
      ("white", 598, "Sony S-Log3 technical summary: 90% = 598")]),
    ("arriLogC3", "bt709", "ARRI Wide Gamut 3",
     lambda e: log_decoding_ARRILogC3(colour.models.full_to_legal(e, BITS)),
     [("gray", 400, "ARRI LogC3 EI 800: 18% = 400"),
      ("white", int(round(1023 * float(log_encoding_ARRILogC3(0.9)))), "colour-science encoding of 90%")]),
    ("vLog", "bt709", "V-Gamut",
     lambda e: log_decoding_VLog(e, in_normalised_code_value=False),
     [("gray", 433, "Panasonic V-Log reference manual: 18% = 433"),
      ("white", 602, "Panasonic V-Log reference manual: 90% = 602")]),
    ("appleLog", "bt2020", "ITU-R BT.2020",
     log_decoding_AppleLogProfile,
     [("gray", legal_code(float(log_encoding_AppleLogProfile(0.18))), "colour-science encoding of 18%"),
      ("white", legal_code(float(log_encoding_AppleLogProfile(0.9))), "colour-science encoding of 90%")]),
    ("hlgRec2020", "bt2020", "ITU-R BT.2020",
     hlg,
     [("gray", legal_code(0.38), "ITU-R BT.2408: 18% gray at 38% signal"),
      ("white", legal_code(0.75), "ITU-R BT.2408: reference white at 75% signal")]),
]
CHROMA = (450, 600)  # a saturated legal-range Cb, Cr pair, to catch a wrong matrix
WEIGHTS = {"bt709": colour.WEIGHTS_YCBCR["ITU-R BT.709"], "bt2020": colour.WEIGHTS_YCBCR["ITU-R BT.2020"]}
# Linear sRGB / Rec.709 with the matrix derived from its primaries (as the engine does),
# not IEC 61966-2-1's 4-digit rounded matrix, which is ~2e-4 off neutral.
WORKING = colour.RGB_Colourspace("Linear sRGB (derived)", RGB_COLOURSPACES["sRGB"].primaries,
                                 RGB_COLOURSPACES["sRGB"].whitepoint, use_derived_matrix_RGB_to_XYZ=True,
                                 use_derived_matrix_XYZ_to_RGB=True)


def to_full(y, cb, cr):
    """The same signal coded in full range (BT.2100 full range, 10-bit)."""
    return (int(round((y - 64) / 876 * 1023)),
            int(round((cb - 512) / 896 * 1023 + 512)),
            int(round((cr - 512) / 896 * 1023 + 512)))


def decode(case, ycbcr, legal):
    _, matrix, gamut, decode_signal, _ = case
    signal = colour.YCbCr_to_RGB(np.array(ycbcr, dtype=float), K=WEIGHTS[matrix], in_bits=BITS,
                                 in_legal=legal, in_int=True, out_legal=False, out_int=False)
    camera = np.array([float(decode_signal(c)) for c in signal])
    return colour.RGB_to_RGB(camera, RGB_COLOURSPACES[gamut], WORKING, chromatic_adaptation_transform=None)


print("// Generated by Tools/color-references/video_signal.py (colour-science "
      f"{colour.__version__}). Do not edit.")
print("@testable import EmulsionCore")
print()
print("extension VideoSignalReference {")
print("    static let all: [VideoSignalReference] = [")
for case in INPUTS:
    name, matrix, _, _, patches = case
    legal_patches = [(label, (y, 512, 512), source) for label, y, source in patches]
    legal_patches.append(("chroma", (patches[0][1], *CHROMA), "saturated Cb/Cr on the gray code"))
    for range_name in ("legal", "full"):
        for label, code, source in legal_patches:
            ycbcr = code if range_name == "legal" else to_full(*code)
            rgb = decode(case, ycbcr, range_name == "legal")
            print(f"        // {source}")
            print(f"        .init(space: .{name}, range: .{range_name}, matrix: .{matrix}, patch: \"{label}\", "
                  f"code: [{ycbcr[0]}, {ycbcr[1]}, {ycbcr[2]}], "
                  f"sceneLinear: [{rgb[0]:.9f}, {rgb[1]:.9f}, {rgb[2]:.9f}]),")
print("    ]")
print("}")
